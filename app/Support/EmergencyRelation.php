        'พ่อ' => 'พ่อ', 'บิดา' => 'พ่อ', 'ป๊า' => 'พ่อ', 'ปะป๊า' => 'พ่อ', 'คุณพ่อ' => 'พ่อ',
        'แม่' => 'แม่', 'มารดา' => 'แม่', 'ม๊า' => 'แม่', 'มะม๊า' => 'แม่', 'มาม้า' => 'แม่', 'หม่าม้า' => 'แม่',
