 *
 * เก็บเป็นข้อความ ไม่ใช่ enum: ตัวเลือกเป็นแค่ทางลัด ลูกค้าพิมพ์เองได้ ("อื่น ๆ") และ
 * แบบฟอร์มแต่ละที่เรียกไม่เหมือนกัน (แม่ / มารดา) — แปลงให้ตรงฟอร์มที่ config/form_fill.php
 *
 * รายการ OPTIONS ซ้ำอยู่ในเว็บ (resources/js/lib/emergencyRelation.js) และแอป
 * (lib/utils/emergency_relation.dart) ต้องตรงกัน
 */
class EmergencyRelation
{
    public const OPTIONS = ['พ่อ', 'แม่', 'สามี', 'ภรรยา', 'แฟน', 'พี่น้อง', 'ลูก', 'ญาติ', 'เพื่อน'];

    public const MAX_LENGTH = 50;

    /**
     * คำในช่องผู้ติดต่อที่บอกความสัมพันธ์ได้ → ค่าที่ส่งออก
     *
     * ดูทีละคำ (ตัดที่ช่องว่าง วงเล็บ / , -) และต้องตรงทั้งคำหลังตัด "คุณ" ข้างหน้า —
     * คำสั้นอย่าง "ตา" "อา" "น้า" อยู่ในชื่อคนเยอะ ("ตาล" "อาทิตย์") จึงไม่ดูแบบมีอยู่ในคำ
     */
