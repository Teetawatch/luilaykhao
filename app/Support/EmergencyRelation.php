        'friend' => 'เพื่อน', 'relative' => 'ญาติ',
    ];

    /**
     * คำที่ขึ้นต้นด้วยความสัมพันธ์แล้วตามด้วยชื่อ ("แม่สมศรี" "พี่สาวต้น") — เฉพาะคำที่ยาว
     * พอจะไม่ใช่ส่วนหนึ่งของชื่อคน ("พี่" "น้อง" "ลูก" ใช้นำชื่อเล่นกันทั่วไป จึงไม่อยู่ที่นี่)
     */
    private const PREFIXES = [
        'คุณแม่' => 'แม่', 'คุณพ่อ' => 'พ่อ', 'แม่' => 'แม่', 'พ่อ' => 'พ่อ',
        'พี่สาว' => 'พี่น้อง', 'พี่ชาย' => 'พี่น้อง', 'น้องสาว' => 'พี่น้อง', 'น้องชาย' => 'พี่น้อง',
        'สามี' => 'สามี', 'ภรรยา' => 'ภรรยา', 'แฟน' => 'แฟน',
    ];

    /** ค่าที่บันทึก — ช่องว่าง = null, ตัดความยาวให้พอดีคอลัมน์ */
    public static function clean(mixed $value): ?string
    {
        $value = trim(preg_replace('/\s+/u', ' ', (string) $value) ?? '');

        return $value === '' ? null : mb_substr($value, 0, self::MAX_LENGTH);
    }

    /** ความสัมพันธ์ที่ลูกค้าเลือกไว้ ถ้าไม่มีเดาจากช่องผู้ติดต่อ ("" = เดาไม่ได้) */
    public static function resolve(?string $stored, ?string $contact): string
    {
        return self::clean($stored) ?? self::guess($contact);
    }

    /** เดาความสัมพันธ์จากช่อง "ผู้ติดต่อฉุกเฉิน" ของใบจองเก่า — ไม่แน่ใจ = "" */
    public static function guess(?string $contact): string
    {
        $tokens = preg_split('/[\s()\[\]\/,\-–:;.·|]+/u', mb_strtolower(trim((string) $contact)), -1, PREG_SPLIT_NO_EMPTY) ?: [];

        foreach ($tokens as $token) {
            $bare = preg_replace('/^คุณ/u', '', $token);
            if (isset(self::WORDS[$token])) {
                return self::WORDS[$token];
            }
            if ($bare !== '' && isset(self::WORDS[$bare])) {
                return self::WORDS[$bare];
            }
        }

        foreach ($tokens as $token) {
            foreach (self::PREFIXES as $prefix => $relation) {
                // ต้องมีชื่อตามหลังจริง — "แม่" เดี่ยว ๆ จับได้แล้วข้างบน
                if (mb_strlen($token) > mb_strlen($prefix) + 1 && str_starts_with($token, $prefix)) {
                    return $relation;
                }
            }
        }

        return '';
    }
}
