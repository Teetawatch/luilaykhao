        'ลูก' => 'ลูก', 'ลูกสาว' => 'ลูก', 'ลูกชาย' => 'ลูก', 'บุตร' => 'ลูก', 'บุตรสาว' => 'ลูก', 'บุตรชาย' => 'ลูก',
